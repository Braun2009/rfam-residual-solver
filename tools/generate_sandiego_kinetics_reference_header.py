#!/usr/bin/env python3
"""Generate the RFAM C++ reference-state header for San Diego kinetics checks.

Embeds the three Cantera equilibrium reference states (T, p, mole fractions,
forward/reverse rates of progress, Kc) so the C++ rate kernel can be validated
without Cantera at RFAM build time.
"""

from __future__ import annotations

import argparse
import json
import math
import sys
from pathlib import Path


DEFAULT_BUNDLE = Path("tests/reference/sandiego_runtime_bundle_v1.json")
DEFAULT_OUTPUT = Path("src/thermo/SandiegoKineticsReference.H")


def esc(value: float) -> str:
    return format(value, ".17g")


def generate(bundle_path: Path, output_path: Path) -> None:
    document = json.loads(bundle_path.read_text(encoding="ascii"))
    if document["schema"] != "rfam.sandiego-runtime-bundle/v1":
        raise RuntimeError("unsupported bundle schema")
    species = document["species"]
    references = document["rate_reference_states"]
    if len(references) != 3:
        raise RuntimeError("expected 3 reference states")

    lines: list[str] = []
    lines.append("/* Auto-generated by tools/generate_sandiego_kinetics_reference_header.py. */")
    lines.append("/* San Diego rate-reference states (Cantera equilibrium); DO NOT EDIT.  */")
    lines.append("")
    lines.append("#ifndef SandiegoKineticsReference_H")
    lines.append("#define SandiegoKineticsReference_H")
    lines.append("")
    lines.append("namespace Foam {")
    lines.append("namespace SandiegoKinetics {")
    lines.append("")
    lines.append("struct SandiegoReferenceState")
    lines.append("{")
    lines.append("    const char* id;")
    lines.append("    double T, p;             // K, Pa")
    lines.append("    double X[59];            // equilibrium mole fractions (species order)")
    lines.append("    double forwardRop[271];  // kmol/m3/s")
    lines.append("    double reverseRop[271];  // kmol/m3/s")
    lines.append("    double Kc[271];          // kmol,m,s concentration basis")
    lines.append("};")
    lines.append("")
    lines.append("constexpr int nReferenceStates = 3;")
    lines.append("")
    lines.append("const SandiegoReferenceState referenceStates[nReferenceStates] = {")
    for state in references:
        x = [0.0] * len(species)
        for name, value in state["mole_fractions"].items():
            index = next(i for i, row in enumerate(species) if row["name"] == name)
            x[index] = value
        lines.append("    SandiegoReferenceState{")
        lines.append(f'        "{state["id"]}",')
        lines.append(f"        {esc(state['temperature_K'])}, {esc(state['pressure_Pa'])},")
        lines.append("        { " + ", ".join(esc(v) for v in x) + " },")
        lines.append("        { " + ", ".join(
            esc(v) for v in state["forward_rates_of_progress_kmol_m3_s"]) + " },")
        lines.append("        { " + ", ".join(
            esc(v) for v in state["reverse_rates_of_progress_kmol_m3_s"]) + " },")
        lines.append("        { " + ", ".join(
            esc(v) for v in state["equilibrium_constants"]) + " }")
        lines.append("    },")
    lines.append("};")
    lines.append("")
    lines.append("} // namespace SandiegoKinetics")
    lines.append("} // namespace Foam")
    lines.append("")
    lines.append("#endif")
    lines.append("")

    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text("\n".join(lines), encoding="ascii")
    print(f"SANDIEGO_KINETICS_REFERENCE_HEADER_PASS states={len(references)} "
          f"output={output_path}")


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--bundle", type=Path, default=DEFAULT_BUNDLE)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    args = parser.parse_args()
    try:
        generate(args.bundle.resolve(), args.output.resolve())
    except (OSError, KeyError, ValueError, json.JSONDecodeError, RuntimeError) as error:
        print(f"SANDIEGO_KINETICS_REFERENCE_HEADER_FAIL {error}", file=sys.stderr)
        return 2
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
