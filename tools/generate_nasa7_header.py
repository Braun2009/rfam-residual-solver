#!/usr/bin/env python3
"""generate_nasa7_header.py - NASA-7 polynomials for the GERG UDRGM ideal
term, read directly from the Cantera solution (robust, no chemkin parsing)."""
import os
import cantera as ct

SRC = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                   "..", "tests", "reference", "sandiego30_fluent.yaml")
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                   "..", "src", "fluent", "GergUdrgmNasa7.H")

g = ct.Solution(SRC)
lines = []
lines.append("/* Auto-generated by tools/generate_nasa7_header.py from sandiego30_fluent.yaml. */")
lines.append("#ifndef GergUdrgmNasa7_H")
lines.append("#define GergUdrgmNasa7_H")
lines.append("")
lines.append("typedef struct Nasa7Species {")
lines.append("    const char* name;")
lines.append("    double mw;      // kg/kmol")
lines.append("    double Tlow, Tmid, Thigh;")
lines.append("    double lo[7];   // a1..a7 low")
lines.append("    double hi[7];   // a1..a7 high")
lines.append("} Nasa7Species;")
lines.append("")
lines.append("static const Nasa7Species GERG_NASA7[] = {")
for i in range(g.n_species):
    sp = g.species(i)
    th = sp.thermo
    name = sp.name
    mw = g.molecular_weights[i]
    try:
        coefs = th.coeffs  # (15,): [Tmid, hi7, lo7]
        tmid = coefs[0]
        hi = [float(x) for x in coefs[1:8]]
        lo = [float(x) for x in coefs[8:15]]
        tmin, tmax = th.min_temp, th.max_temp
    except AttributeError:
        tmin = tmax = tmid = 300.0
        lo = hi = [0.0] * 7

    def fmt(a):
        return "{" + ", ".join("%.16g" % x for x in a) + "}"

    lines.append('    {"%s", %.6f, %.1f, %.1f, %.1f,' % (name, mw, tmin, tmid, tmax))
    lines.append("     %s, %s}," % (fmt(lo), fmt(hi)))
lines.append("};")
lines.append("")
lines.append("static const int GERG_NASA7_N = sizeof(GERG_NASA7) / sizeof(GERG_NASA7[0]);")
lines.append("")
lines.append("#endif")
os.makedirs(os.path.dirname(OUT), exist_ok=True)
open(OUT, "w", encoding="utf-8").write("\n".join(lines) + "\n")
print("wrote", OUT)
