#!/usr/bin/env python3
"""Generate an RFAM C++ static NASA-7 data table for the 59-species San Diego set.

The 59-species mechanism species are NOT part of the production 9-species
SpeciesRegistry. This tool generates a standalone, dependency-free C++ header
(SandiegoNasa7Data.H) that carries the San Diego NASA-7 coefficients, molecular
weights and element composition. Cantera is used only offline to generate the
source bundle; the emitted header is pure C++ with no third-party dependency.

Nothing here mutates the production SpeciesRegistry / NASA7Thermo. The 9->59
runtime reconciliation is a later step.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path


DEFAULT_BUNDLE = Path("tests/reference/sandiego_runtime_bundle_v1.json")
DEFAULT_OUTPUT = Path("src/thermo/SandiegoNasa7Data.H")


def esc(value: float) -> str:
    return format(value, ".17g")


def emit_species(species: dict, index: int) -> list[str]:
    name = species["name"]
    thermo = species["thermo"]
    low, high = thermo["data"]
    tlow, tcommon, thigh = thermo["temperature-ranges"]
    elements = species["elements"]
    n_c = int(elements.get("C", 0))
    n_h = int(elements.get("H", 0))
    n_o = int(elements.get("O", 0))
    n_n = int(elements.get("N", 0))
    return [
        "    SandiegoSpeciesData{",
        f'        "{name}",',
        f"        {esc(tlow)}, {esc(tcommon)}, {esc(thigh)},",
        "        { " + ", ".join(esc(v) for v in low) + " },",
        "        { " + ", ".join(esc(v) for v in high) + " },",
        f"        {esc(species['molecular_weight_kg_per_mol'])},"
        f" {n_c}, {n_h}, {n_o}, {n_n}",
        "    },",
    ]


def generate(bundle_path: Path, output_path: Path) -> None:
    document = json.loads(bundle_path.read_text(encoding="ascii"))
    if document["schema"] != "rfam.sandiego-runtime-bundle/v1":
        raise RuntimeError("unsupported bundle schema")
    species = document["species"]
    if len(species) != 59:
        raise RuntimeError("expected 59 species")
    for row in species:
        if row["thermo"]["model"] != "NASA7":
            raise RuntimeError(f"non-NASA7 species {row['name']}")

    lines: list[str] = []
    lines.append("/* Auto-generated by tools/generate_sandiego_nasa7_header.py. */")
    lines.append("/* San Diego 59-species NASA-7 thermo; DO NOT EDIT BY HAND.    */")
    lines.append("")
    lines.append("#ifndef SandiegoNasa7Data_H")
    lines.append("#define SandiegoNasa7Data_H")
    lines.append("")
    lines.append("#include <cmath>")
    lines.append("#include <string>")
    lines.append("#include <vector>")
    lines.append("")
    lines.append("namespace Foam {")
    lines.append("namespace SandiegoNasa7 {")
    lines.append("")
    lines.append("namespace {")
    lines.append("constexpr double Runiv = 8.314462618;")
    lines.append("constexpr double Tref = 298.15;")
    lines.append("}")
    lines.append("")
    lines.append("struct SandiegoSpeciesData")
    lines.append("{")
    lines.append("    const char* name;")
    lines.append("    double Tlow, Tcommon, Thigh;")
    lines.append("    double lo[7];")
    lines.append("    double hi[7];")
    lines.append("    double mw;             // kg/mol")
    lines.append("    int nC, nH, nO, nN;")
    lines.append("};")
    lines.append("")
    lines.append("constexpr int nSpecies = 59;")
    lines.append("")
    lines.append("const SandiegoSpeciesData species[nSpecies] = {")
    for index, row in enumerate(species):
        lines.extend(emit_species(row, index))
    lines.append("};")
    lines.append("")
    lines.append("inline int index(const std::string& name)")
    lines.append("{")
    lines.append("    for (int i = 0; i < nSpecies; ++i)")
    lines.append("        if (name == species[i].name) return i;")
    lines.append("    return -1;")
    lines.append("}")
    lines.append("")
    lines.append("inline const double* rangeCoeffs(const SandiegoSpeciesData& s, double T)")
    lines.append("{")
    lines.append("    return T < s.Tcommon ? s.lo : s.hi;")
    lines.append("}")
    lines.append("")
    lines.append("// San Diego coefficients are evaluated as pure polynomials (no")
    lines.append("// clamping), matching Cantera/CEA practice for states outside the")
    lines.append("// nominal NASA-7 range (e.g. C3H5 Thigh=3000 K at T=3800 K).")
    lines.append("inline double cpR(const double* a, double T)")
    lines.append("{")
    lines.append("    return a[0] + T * (a[1] + T * (a[2] + T * (a[3] + T * a[4])));")
    lines.append("}")
    lines.append("")
    lines.append("inline double hOverR(const double* a, double T)")
    lines.append("{")
    lines.append("    return T * (a[0] + T * (a[1] / 2.0 + T * (a[2] / 3.0 + T * (a[3] / 4.0 + T * (a[4] / 5.0))))) + a[5];")
    lines.append("}")
    lines.append("")
    lines.append("// cp [J/(mol K)] (pure polynomial evaluation).")
    lines.append("inline double cpMole(int i, double T)")
    lines.append("{")
    lines.append("    const SandiegoSpeciesData& s = species[i];")
    lines.append("    return Runiv * cpR(rangeCoeffs(s, T), T);")
    lines.append("}")
    lines.append("")
    lines.append("// absolute molar enthalpy [J/mol] (pure polynomial evaluation).")
    lines.append("inline double hMole(int i, double T)")
    lines.append("{")
    lines.append("    const SandiegoSpeciesData& s = species[i];")
    lines.append("    return Runiv * hOverR(rangeCoeffs(s, T), T);")
    lines.append("}")
    lines.append("")
    lines.append("// standard molar entropy [J/(mol K)] (pure polynomial evaluation).")
    lines.append("inline double sMole(int i, double T)")
    lines.append("{")
    lines.append("    const SandiegoSpeciesData& s = species[i];")
    lines.append("    const double* a = rangeCoeffs(s, T);")
    lines.append("    return Runiv * (a[0] * std::log(T) + T * (a[1] + T * (a[2] / 2.0 + T * (a[3] / 3.0 + T * (a[4] / 4.0)))) + a[6]);")
    lines.append("}")
    lines.append("")
    lines.append("} // namespace SandiegoNasa7")
    lines.append("} // namespace Foam")
    lines.append("")
    lines.append("#endif")
    lines.append("")

    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text("\n".join(lines), encoding="ascii")
    print(f"SANDIEGO_NASA7_HEADER_PASS species={len(species)} output={output_path}")


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--bundle", type=Path, default=DEFAULT_BUNDLE)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    args = parser.parse_args()
    try:
        generate(args.bundle.resolve(), args.output.resolve())
    except (OSError, KeyError, ValueError, json.JSONDecodeError) as error:
        print(f"SANDIEGO_NASA7_HEADER_FAIL {error}", file=sys.stderr)
        return 2
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
