#ifndef CryogenicTransportTable_H
#define CryogenicTransportTable_H

/*---------------------------------------------------------------------------*\
    CryogenicTransportTable - strict runtime dense-fluid transport table.

    Reads the frozen pure-fluid (T, rho) transport table generated by
    `tools/generate_cryogenic_transport_table.py` (schema
    `rfam.cryogenic-transport-runtime-table/v1`, CoolProp 7.2.0 HEOS pinned
    at git revision 98b3523d5daa98454618d381d2ae53f7471d216b).

    Strict semantics (no silent fallback):
      - the schema line and all required columns must match;
      - density nodes must be identical across all temperature layers;
      - two-phase states are recorded as NaN in the table and are rejected
        via the per-layer saturation endpoints (rho_vapor_sat / rho_liquid_sat);
      - a query inside the two-phase dome, outside the table bounds, or
        touching a NaN node returns OUT_OF_RANGE / TWO_PHASE and never
        clamps, extrapolates, or substitutes a gas value;
      - interpolation is bilinear in (T, rho) over single-phase nodes only.

    This table is a pure-fluid backend only.  It is NOT a dense-mixture
    model, a two-phase effective closure, or evidence that
    `ModelCapabilities::denseCryogenicTransport` is ready.
\*---------------------------------------------------------------------------*/

#include <algorithm>
#include <cstddef>
#include <limits>
#include <optional>
#include <string>
#include <vector>

namespace Foam
{

enum class CryogenicTransportTableStatus
{
    SUCCESS,
    UNKNOWN_SPECIES,
    MISSING_TABLE,
    INVALID_SCHEMA,
    INVALID_COLUMNS,
    NON_MONOTONIC_TEMPERATURE,
    MISALIGNED_DENSITY_NODES,
    INVALID_NODE_DATA,
    OUT_OF_RANGE,
    TWO_PHASE,
    INVALID_INPUT,
    PROVENANCE_MISMATCH
};

const char* cryogenicTransportTableStatusName(
    CryogenicTransportTableStatus status);

struct CryogenicTransportProperties
{
    double mu = std::numeric_limits<double>::quiet_NaN();      // Pa s
    double kappa = std::numeric_limits<double>::quiet_NaN();   // W/(m K)
};

struct CryogenicTransportTableResult
{
    CryogenicTransportTableStatus status =
        CryogenicTransportTableStatus::UNKNOWN_SPECIES;
    std::optional<CryogenicTransportProperties> properties;
    double temperatureK = std::numeric_limits<double>::quiet_NaN();
    double densityKgM3 = std::numeric_limits<double>::quiet_NaN();

    bool success() const
    {
        return status == CryogenicTransportTableStatus::SUCCESS
            && properties.has_value();
    }
};

// Strict pure-fluid dense transport table.
class CryogenicTransportTable
{
public:
    // Loads the frozen CSV.  `path` is the canonical table file.
    // `expectedSha256` is the externally frozen SHA-256 of the CSV bytes;
    // pass an empty string to skip the byte hash check (not recommended).
    bool load(const std::string& path,
              const std::string& expectedSha256 = std::string());

    bool has(const std::string& species) const;

    // Bilinear (T, rho) lookup of mu/kappa for a single-phase state.
    // Returns TWO_PHASE when the density lies between the layer saturation
    // endpoints, OUT_OF_RANGE outside the table, and SUCCESS otherwise.
    CryogenicTransportTableResult evaluate(
        const std::string& species,
        double temperatureK,
        double densityKgM3) const;

    // Per-species supported temperature/rho bounds (for diagnostics).
    bool temperatureBounds(
        const std::string& species,
        double& minimum,
        double& maximum) const;

    std::string provenanceManifest() const { return provenanceManifest_; }
    std::string provenanceSha256() const { return provenanceSha256_; }

private:
    struct Layer
    {
        double temperatureK = std::numeric_limits<double>::quiet_NaN();
        double rhoVaporSatKgM3 = std::numeric_limits<double>::quiet_NaN();
        double rhoLiquidSatKgM3 = std::numeric_limits<double>::quiet_NaN();
        std::vector<double> rho;      // shared node coordinates
        std::vector<double> mu;       // NaN marks two-phase / unavailable
        std::vector<double> kappa;
    };

    struct SpeciesTable
    {
        std::string species;
        std::vector<double> densityNodes;
        std::vector<Layer> layers;    // sorted by temperature
    };

    const SpeciesTable* find(const std::string& species) const;

    static bool near(double a, double b, double tolerance)
    {
        return std::abs(a - b) <= tolerance * std::max({std::abs(a),
            std::abs(b), 1.0});
    }

    std::vector<SpeciesTable> tables_;
    std::string provenanceManifest_;
    std::string provenanceSha256_;
};

} // End namespace Foam

#endif
