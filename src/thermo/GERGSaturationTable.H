#ifndef GERGSaturationTable_H
#define GERGSaturationTable_H

/*---------------------------------------------------------------------------*\
    GERGSaturationTable - bubble-pressure (saturation-line) table.

    Reads the frozen table generated by
    tools/generate_gerg_saturation_table.py (schema rfam.gerg-saturation-
    table/v2): torch-flash binary_bubble_point cross-checked against
    CoolProp HEOS (<0.15% deviation on every row).  v2 (2026-08-04):
    e_liquid/e_vapor converted from CoolProp absolute U to the RFAM
    NASA7 sensible reference (h_sens(298.15 K)=0), so HEM two-phase
    internal energies are comparable with the solver's sensible e.

    Covers: pure O2 (60-154 K), pure C3H8 (90-369 K), O2/C3H8 at
    xO2 in {0.50, 0.75, 0.95} (90-150 K).  The propane-rich deep-cold
    region (xO2 < 0.5) is excluded (dual-implementation root-solver
    divergence, 2026-08-03).

    Purpose: two-phase detection for single-phase recovery paths —
    e.g. the Mayer transcritical jet where diffusive mixing drives
    subcritical liquid O2 into the two-phase internal-energy range and the
    single-phase recovery correctly fails closed.  A (T, p, xO2) query
    returns the phase classification WITHOUT a full flash.
\*---------------------------------------------------------------------------*/

#include <algorithm>
#include <cmath>
#include <cstddef>
#include <fstream>
#include <limits>
#include <optional>
#include <sstream>
#include <string>
#include <vector>

namespace Foam
{

enum class SaturationPhase
{
    SUPPORTED_SINGLE_PHASE,   // p >= p_sat (compressed liquid / gas at p>=sat)
    TWO_PHASE_CANDIDATE,      // p < p_sat at this T: inside the dome
    OUT_OF_TABLE,             // (T, xO2) not covered
    INVALID_INPUT
};

class GERGSaturationTable
{
public:
    bool load(const std::string& path)
    {
        std::ifstream input(path);
        if (!input) { provenance_ = "missing:" + path; return false; }
        rows_.clear();
        std::string line;
        std::vector<std::string> header;
        while (std::getline(input, line))
        {
            if (line.empty()) continue;
            if (line[0] == '#') continue;
            std::vector<std::string> fields;
            std::stringstream ss(line);
            std::string f;
            while (std::getline(ss, f, ',')) fields.push_back(trim(f));
            if (header.empty()) { header = fields; continue; }
            if (fields.size() != header.size()) continue;
            auto col = [&](const std::string& name) -> int
            {
                for (std::size_t i = 0; i < header.size(); ++i)
                    if (header[i] == name) return static_cast<int>(i);
                return -1;
            };
            const int cT = col("temperature_k");
            const int cX = col("x_o2");
            const int cP = col("p_sat_pa");
            const int cRL = col("rho_liquid_kgm3");
            const int cRV = col("rho_vapor_kgm3");
            const int cEL = col("e_liquid_j_kg");
            const int cEV = col("e_vapor_j_kg");
            const int cY = col("y_o2_vapor");
            if (cT < 0 || cX < 0 || cP < 0) continue;
            try
            {
                Row row;
                row.T = std::stod(fields[static_cast<std::size_t>(cT)]);
                row.xO2 = std::stod(fields[static_cast<std::size_t>(cX)]);
                row.pSat = std::stod(fields[static_cast<std::size_t>(cP)]);
                row.rhoL = (cRL >= 0)
                    ? std::stod(fields[static_cast<std::size_t>(cRL)])
                    : std::numeric_limits<double>::quiet_NaN();
                row.rhoV = (cRV >= 0)
                    ? std::stod(fields[static_cast<std::size_t>(cRV)])
                    : std::numeric_limits<double>::quiet_NaN();
                row.eL = (cEL >= 0)
                    ? std::stod(fields[static_cast<std::size_t>(cEL)])
                    : std::numeric_limits<double>::quiet_NaN();
                row.eV = (cEV >= 0)
                    ? std::stod(fields[static_cast<std::size_t>(cEV)])
                    : std::numeric_limits<double>::quiet_NaN();
                row.yO2 = (cY >= 0)
                    ? std::stod(fields[static_cast<std::size_t>(cY)])
                    : std::numeric_limits<double>::quiet_NaN();
                if (std::isfinite(row.T) && std::isfinite(row.xO2)
                    && std::isfinite(row.pSat) && row.pSat > 0.0)
                    rows_.push_back(row);
            }
            catch (...) { continue; }
        }
        provenance_ = "loaded:" + path;
        return !rows_.empty();
    }

    std::string provenance() const { return provenance_; }

    // Two-phase check at (T, p, xO2).  xO2 is snapped to the nearest
    // table composition level (0.5/0.75/0.95/pure).
    SaturationPhase classify(double T, double p, double xO2,
                             double rho = std::numeric_limits<double>::quiet_NaN()) const
    {
        if (!std::isfinite(T) || !std::isfinite(p) || !std::isfinite(xO2)
            || T <= 0.0 || p <= 0.0)
            return SaturationPhase::INVALID_INPUT;
        const double pSat = saturationPressure(T, xO2);
        if (!std::isfinite(pSat))
            return SaturationPhase::OUT_OF_TABLE;
        if (p < pSat)
            return SaturationPhase::TWO_PHASE_CANDIDATE;
        // Density check: a recovered single-phase root whose density lies
        // between the saturated liquid and vapour densities is a spurious
        // meta-stable solution (e.g. dense vapour inside the dome): treat
        // as two-phase candidate for the recovery path.
        if (std::isfinite(rho) && rho > 0.0)
        {
            double rhoV = 0.0, rhoL = 0.0;
            if (saturationDensityRange(T, xO2, rhoV, rhoL)
                && rho > rhoV && rho < rhoL)
                return SaturationPhase::TWO_PHASE_CANDIDATE;
        }
        return SaturationPhase::SUPPORTED_SINGLE_PHASE;
    }

    // Coexisting vapour composition (O2 mole fraction) at (T, xO2), from
    // the teqp GERG-2008 trace (schema v3).  NaN outside the stable teqp
    // segment (fail closed).  Linear interpolation at the nearest level.
    double vaporComposition(double T, double xO2) const
    {
        const auto level = levelRows(xO2);
        if (level.empty()) return std::numeric_limits<double>::quiet_NaN();
        if (T < level.front()->T || T > level.back()->T)
            return std::numeric_limits<double>::quiet_NaN();
        for (std::size_t i = 0; i + 1 < level.size(); ++i)
        {
            const double t0 = level[i]->T, t1 = level[i + 1]->T;
            if (T >= t0 && T <= t1)
            {
                const double w = (T - t0) / (t1 - t0);
                const double y0 = level[i]->yO2;
                const double y1 = level[i + 1]->yO2;
                if (!std::isfinite(y0) || !std::isfinite(y1))
                    return std::numeric_limits<double>::quiet_NaN();
                return y0 + w * (y1 - y0);
            }
        }
        return level.back()->yO2;
    }

    // Saturated liquid/vapour densities at (T, xO2) (linear T interpolation
    // at the nearest composition level).
    bool saturationDensityRange(double T, double xO2,
                                double& rhoV, double& rhoL) const
    {
        return saturationEndpoints(T, xO2, rhoV, rhoL, nullptr, nullptr);
    }

    // Full saturation endpoints (rho and internal energy of both phases).
    bool saturationEndpoints(double T, double xO2,
                             double& rhoV, double& rhoL,
                             double* eV, double* eL) const
    {
        const auto level = levelRows(xO2);
        if (level.empty())
            return false;
        if (T < level.front()->T || T > level.back()->T)
            return false;
        for (std::size_t i = 0; i + 1 < level.size(); ++i)
        {
            const double t0 = level[i]->T, t1 = level[i + 1]->T;
            if (T >= t0 && T <= t1)
            {
                const double w = (T - t0) / (t1 - t0);
                const Row& a = *level[i];
                const Row& b = *level[i + 1];
                if (!std::isfinite(a.rhoL) || !std::isfinite(a.rhoV)
                    || !std::isfinite(b.rhoL) || !std::isfinite(b.rhoV))
                    return false;
                if (eV && (!std::isfinite(a.eV) || !std::isfinite(b.eV)))
                    return false;
                if (eL && (!std::isfinite(a.eL) || !std::isfinite(b.eL)))
                    return false;
                rhoV = a.rhoV + w * (b.rhoV - a.rhoV);
                rhoL = a.rhoL + w * (b.rhoL - a.rhoL);
                if (eV) *eV = a.eV + w * (b.eV - a.eV);
                if (eL) *eL = a.eL + w * (b.eL - a.eL);
                return rhoL > rhoV && rhoV > 0.0;
            }
        }
        return false;
    }

    // Bubble pressure at (T, xO2) with linear T interpolation at the
    // nearest composition level; NaN when outside the table.
    double saturationPressure(double T, double xO2) const
    {
        if (rows_.empty()) return std::numeric_limits<double>::quiet_NaN();
        const auto level = levelRows(xO2);
        if (level.empty())
            return std::numeric_limits<double>::quiet_NaN();
        if (T < level.front()->T || T > level.back()->T)
            return std::numeric_limits<double>::quiet_NaN();
        for (std::size_t i = 0; i + 1 < level.size(); ++i)
        {
            const double t0 = level[i]->T, t1 = level[i + 1]->T;
            if (T >= t0 && T <= t1)
            {
                const double w = (T - t0) / (t1 - t0);
                return level[i]->pSat
                    + w * (level[i + 1]->pSat - level[i]->pSat);
            }
        }
        return level.back()->pSat;
    }

private:
    struct Row
    {
        double T;
        double xO2;
        double pSat;
        double rhoL;
        double rhoV;
        double eL;
        double eV;
        // Coexisting-phase vapour composition (O2 mole fraction) from the
        // teqp GERG-2008 trace (schema v3); NaN for pure rows and for
        // rows outside the stable teqp segment (fail closed).
        double yO2 = std::numeric_limits<double>::quiet_NaN();
    };

    static std::string trim(const std::string& value)
    {
        std::size_t b = value.find_first_not_of(" \t\r\n");
        if (b == std::string::npos) return std::string();
        std::size_t e = value.find_last_not_of(" \t\r\n");
        return value.substr(b, e - b + 1);
    }

    std::vector<const Row*> levelRows(double xO2) const
    {
        double best = std::numeric_limits<double>::infinity();
        std::vector<const Row*> out;
        for (const Row& r : rows_)
        {
            const double d = std::abs(r.xO2 - xO2);
            if (d < best) { best = d; out.clear(); }
            if (std::abs(d - best) < 1e-12) out.push_back(&r);
        }
        std::sort(out.begin(), out.end(),
                  [](const Row* a, const Row* b) { return a->T < b->T; });
        return out;
    }

    std::vector<Row> rows_;
    std::string provenance_;
};

} // End namespace Foam

#endif
