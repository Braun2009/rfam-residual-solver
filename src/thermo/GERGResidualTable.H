#ifndef GERGResidualTable_H
#define GERGResidualTable_H

/*---------------------------------------------------------------------------*\
    GERGResidualTable - strict runtime GERG-2008 residual-Helmholtz table.

    Reads the frozen (T, rho) table generated by
    tools/generate_gerg_residual_table.py (schema rfam.gerg-residual-table/v1,
    torch-flash multiparameter.gerg-2008, autograd derivatives).

    The GERG residual is defined for every rho (including the dense liquid
    branch where the PR isochoric path has no single-phase root); this is
    the motivation for the GERG adoption as the low-temperature stable-molecule
    kernel.

    Strict semantics:
      - schema line and required columns must match;
      - bilinear interpolation in (T, rho) of a_res and its derivatives;
      - out-of-range queries return OUT_OF_RANGE (never clamp);
      - two-phase states are NOT special: the residual is a continuous
        function of (T, rho) across the dome (the phase topology is a
        separate flash question).

    Pure-fluid table only: composition handling for mixtures is a later
    mixing-rule step (GERG departure terms).
\*---------------------------------------------------------------------------*/

#include <algorithm>
#include <cmath>
#include <cstddef>
#include <fstream>
#include <limits>
#include <optional>
#include <sstream>
#include <string>
#include <vector>

namespace Foam
{

enum class GERGResidualTableStatus
{
    SUCCESS,
    UNKNOWN_SPECIES,
    MISSING_TABLE,
    INVALID_SCHEMA,
    OUT_OF_RANGE,
    INVALID_INPUT
};

struct GERGResidualProperties
{
    double aRes = std::numeric_limits<double>::quiet_NaN();   // J/kg
    double daResDT = std::numeric_limits<double>::quiet_NaN();// J/kg/K
    double d2aResDT2 = std::numeric_limits<double>::quiet_NaN();
    double daResDrho = std::numeric_limits<double>::quiet_NaN();
    double d2aResDrho2 = std::numeric_limits<double>::quiet_NaN();
    double d2aResDTdrho = std::numeric_limits<double>::quiet_NaN();
};

struct GERGResidualTableResult
{
    GERGResidualTableStatus status = GERGResidualTableStatus::UNKNOWN_SPECIES;
    std::optional<GERGResidualProperties> properties;
    double temperatureK = std::numeric_limits<double>::quiet_NaN();
    double densityKgM3 = std::numeric_limits<double>::quiet_NaN();

    bool success() const
    {
        return status == GERGResidualTableStatus::SUCCESS
            && properties.has_value();
    }
};

class GERGResidualTable
{
public:
    bool load(const std::string& path)
    {
        std::ifstream input(path);
        if (!input) { provenanceSha256_ = "missing:" + path; return false; }
        std::vector<std::string> header;
        std::vector<std::vector<std::string>> rows;
        {
            std::string line;
            bool first = true;
            while (std::getline(input, line))
            {
                if (line.empty()) continue;
                std::vector<std::string> fields;
                std::stringstream stream(line);
                std::string field;
                while (std::getline(stream, field, ','))
                    fields.push_back(trim(field));
                if (first) { header = fields; first = false; continue; }
                rows.push_back(fields);
            }
        }
        if (header.empty() || rows.empty())
        { provenanceSha256_ = "empty:" + path; return false; }

        auto col = [&](const std::string& name) -> int
        {
            for (std::size_t i = 0; i < header.size(); ++i)
                if (header[i] == name) return static_cast<int>(i);
            return -1;
        };
        const int cSchema = col("schema_version");
        const int cSp = col("species");
        const int cT = col("temperature_k");
        const int cRho = col("rho_kg_m3");
        const int cA = col("a_res_J_kg");
        const int cdT = col("da_dT_J_kgK");
        const int cdT2 = col("d2a_dT2_J_kgK2");
        const int cdr = col("da_drho_J_kg_per_kgm3");
        const int cdr2 = col("d2a_drho2_J_kg_per_kgm32");
        const int cdTr = col("d2a_dTdrho_J_kgK_per_kgm3");
        if (cSchema < 0 || cSp < 0 || cT < 0 || cRho < 0 || cA < 0
            || cdT < 0 || cdT2 < 0 || cdr < 0 || cdr2 < 0 || cdTr < 0)
        { provenanceSha256_ = "invalid-columns:" + path; return false; }

        struct Raw { double T, rho, a, dT, dT2, dr, dr2, dTr; };
        std::vector<std::pair<std::string, std::vector<Raw>>> grouped;
        for (const auto& fields : rows)
        {
            if (fields.size() != header.size()) continue;
            if (fields[static_cast<std::size_t>(cSchema)]
                != "rfam.gerg-residual-table/v1")
            { provenanceSha256_ = "invalid-schema:" + path; return false; }
            Raw raw;
            if (!parse(fields[static_cast<std::size_t>(cT)], raw.T)
                || !parse(fields[static_cast<std::size_t>(cRho)], raw.rho)
                || !parse(fields[static_cast<std::size_t>(cA)], raw.a)
                || !parse(fields[static_cast<std::size_t>(cdT)], raw.dT)
                || !parse(fields[static_cast<std::size_t>(cdT2)], raw.dT2)
                || !parse(fields[static_cast<std::size_t>(cdr)], raw.dr)
                || !parse(fields[static_cast<std::size_t>(cdr2)], raw.dr2)
                || !parse(fields[static_cast<std::size_t>(cdTr)], raw.dTr))
            { provenanceSha256_ = "invalid-node:" + path; return false; }
            const std::string species = fields[static_cast<std::size_t>(cSp)];
            if (grouped.empty() || grouped.back().first != species)
                grouped.emplace_back(species, std::vector<Raw>());
            grouped.back().second.push_back(raw);
        }

        tables_.clear();
        for (const auto& [species, rawRows] : grouped)
        {
            SpeciesTable table;
            table.species = species;
            for (const auto& raw : rawRows)
            {
                auto& row = table.rows.emplace_back();
                row.T = raw.T; row.rho = raw.rho; row.a = raw.a;
                row.dT = raw.dT; row.dT2 = raw.dT2;
                row.dr = raw.dr; row.dr2 = raw.dr2; row.dTr = raw.dTr;
            }
            // Unique temperatures / densities (sorted).
            std::vector<double> Ts, Rhos;
            for (const auto& row : table.rows)
            {
                if (std::find(Ts.begin(), Ts.end(), row.T) == Ts.end())
                    Ts.push_back(row.T);
                if (std::find(Rhos.begin(), Rhos.end(), row.rho) == Rhos.end())
                    Rhos.push_back(row.rho);
            }
            std::sort(Ts.begin(), Ts.end());
            std::sort(Rhos.begin(), Rhos.end());
            table.temperatures = Ts;
            table.densities = Rhos;
            tables_.push_back(std::move(table));
        }
        provenanceSha256_ = "loaded:" + path;
        return !tables_.empty();
    }

    bool has(const std::string& species) const
    {
        return find(species) != nullptr;
    }

    // Table coverage for a species (density/temperature in kg/m3 / K).
    bool densityRange(const std::string& species,
                      double& rhoMin, double& rhoMax) const
    {
        const SpeciesTable* table = find(species);
        if (!table || table->densities.empty()) return false;
        rhoMin = table->densities.front();
        rhoMax = table->densities.back();
        return true;
    }

    bool temperatureRange(const std::string& species,
                          double& tMin, double& tMax) const
    {
        const SpeciesTable* table = find(species);
        if (!table || table->temperatures.empty()) return false;
        tMin = table->temperatures.front();
        tMax = table->temperatures.back();
        return true;
    }

    GERGResidualTableResult evaluate(
        const std::string& species,
        double T, double rho) const
    {
        GERGResidualTableResult result;
        result.temperatureK = T;
        result.densityKgM3 = rho;
        if (!std::isfinite(T) || !std::isfinite(rho)
            || T <= 0.0 || rho <= 0.0)
        { result.status = GERGResidualTableStatus::INVALID_INPUT; return result; }
        const SpeciesTable* table = find(species);
        if (!table)
        { result.status = GERGResidualTableStatus::UNKNOWN_SPECIES; return result; }
        if (T < table->temperatures.front() || T > table->temperatures.back()
            || rho < table->densities.front() || rho > table->densities.back())
        { result.status = GERGResidualTableStatus::OUT_OF_RANGE; return result; }

        // Bilinear interpolation.
        const std::size_t i0 = bracket(table->temperatures, T);
        const std::size_t j0 = bracket(table->densities, rho);
        const double t0 = table->temperatures[i0];
        const double t1 = table->temperatures[i0 + 1];
        const double r0 = table->densities[j0];
        const double r1 = table->densities[j0 + 1];
        const double wt = (T - t0) / (t1 - t0);
        const double wr = (rho - r0) / (r1 - r0);

        GERGResidualProperties props;
        const double ft = (i0 + 1 < table->temperatures.size()) ? wt : 0.0;
        const double fr = (j0 + 1 < table->densities.size()) ? wr : 0.0;
        // 4 corner nodes
        const auto& n00 = node(*table, i0, j0);
        const auto& n10 = node(*table, i0 + 1, j0);
        const auto& n01 = node(*table, i0, j0 + 1);
        const auto& n11 = node(*table, i0 + 1, j0 + 1);
        auto blend = [&](double v00, double v10, double v01, double v11)
        {
            return (1.0 - ft) * (1.0 - fr) * v00 + ft * (1.0 - fr) * v10
                 + (1.0 - ft) * fr * v01 + ft * fr * v11;
        };
        props.aRes = blend(n00.a, n10.a, n01.a, n11.a);
        props.daResDT = blend(n00.dT, n10.dT, n01.dT, n11.dT);
        props.d2aResDT2 = blend(n00.dT2, n10.dT2, n01.dT2, n11.dT2);
        props.daResDrho = blend(n00.dr, n10.dr, n01.dr, n11.dr);
        props.d2aResDrho2 = blend(n00.dr2, n10.dr2, n01.dr2, n11.dr2);
        props.d2aResDTdrho = blend(n00.dTr, n10.dTr, n01.dTr, n11.dTr);

        if (!std::isfinite(props.aRes))
        { result.status = GERGResidualTableStatus::OUT_OF_RANGE; return result; }
        result.properties = props;
        result.status = GERGResidualTableStatus::SUCCESS;
        return result;
    }

    std::string provenanceSha256() const { return provenanceSha256_; }

private:
    struct Row
    {
        double T, rho, a, dT, dT2, dr, dr2, dTr;
    };
    struct SpeciesTable
    {
        std::string species;
        std::vector<double> temperatures;
        std::vector<double> densities;
        std::vector<Row> rows;

        const Row& at(std::size_t i, std::size_t j) const
        {
            const double T = temperatures[i], rho = densities[j];
            for (const auto& r : rows)
                if (r.T == T && r.rho == rho) return r;
            return rows.front();
        }
    };

    const SpeciesTable* find(const std::string& species) const
    {
        for (const auto& t : tables_)
            if (t.species == species) return &t;
        return nullptr;
    }

    const Row& node(const SpeciesTable& table, std::size_t i, std::size_t j) const
    {
        const double T = table.temperatures[std::min(i, table.temperatures.size()-1)];
        const double rho = table.densities[std::min(j, table.densities.size()-1)];
        for (const auto& r : table.rows)
            if (r.T == T && r.rho == rho) return r;
        return table.rows.front();
    }

    static std::size_t bracket(const std::vector<double>& v, double x)
    {
        std::size_t lo = 0;
        for (; lo + 1 < v.size() && v[lo + 1] <= x; ++lo) {}
        return lo;
    }

    static std::string trim(const std::string& value)
    {
        std::size_t b = value.find_first_not_of(" \t\r\n");
        if (b == std::string::npos) return std::string();
        std::size_t e = value.find_last_not_of(" \t\r\n");
        return value.substr(b, e - b + 1);
    }

    static bool parse(const std::string& text, double& value)
    {
        try
        {
            const std::string t = trim(text);
            std::size_t consumed = 0;
            value = std::stod(t, &consumed);
            return consumed == t.size();
        }
        catch (...) { return false; }
    }

    std::vector<SpeciesTable> tables_;
    std::string provenanceSha256_;
};

} // End namespace Foam

#endif
